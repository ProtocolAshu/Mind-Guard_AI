"""Independent evaluation of the *registered* models through the backend's own loaders
(SHA-256 verified), on the held-out test split. Confirms that what the API serves
reproduces the training report, and writes a Markdown evaluation report.

    PYTHONPATH=backend:. python -m ml.evaluation.evaluate
"""

from __future__ import annotations

import json
from typing import Any

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

from app.providers.classifiers import HybridClassifier, LexiconClassifier, SklearnTextClassifier
from app.risk.features import RISK_FEATURES
from app.risk.scoring import TARGETS, RiskModelRegistry
from ml.common import DATASET_DIR, MODEL_DIR, REPORT_DIR, SEED, grouped_split
from ml.training.train_content import summary
from ml.training.train_risk import metrics, rules_probabilities


def evaluate_risk() -> dict[str, Any]:
    registry = RiskModelRegistry(MODEL_DIR)
    if registry.load_errors or not registry.available:
        raise SystemExit(f"risk registry failed to load: {registry.load_errors}")
    df = pd.read_csv(DATASET_DIR / "risk_training.csv")
    _, _, test = grouped_split(df["group"].to_numpy())
    frame = df.iloc[test]
    X = frame[list(RISK_FEATURES)].to_numpy(dtype=float)
    out: dict[str, Any] = {}
    for target in TARGETS:
        y = frame[f"label_{target}"].to_numpy(dtype=int)
        p = registry.models[target].model.predict_proba(X)[:, 1]
        out[target] = {"model": metrics(y, p), "rules_baseline": metrics(y, rules_probabilities(frame, target)),
                       "version": registry.models[target].version}
    out["by_persona_distraction_auc"] = {}
    for persona, part in frame.groupby("persona"):
        y = part["label_distraction"].to_numpy(dtype=int)
        if 0 < y.mean() < 1:
            p = registry.models["distraction"].model.predict_proba(part[list(RISK_FEATURES)].to_numpy(dtype=float))[:, 1]
            out["by_persona_distraction_auc"][persona] = metrics(y, p)["roc_auc"]
    return out


def evaluate_content() -> dict[str, Any]:
    df = pd.read_csv(DATASET_DIR / "content_captions.csv")
    _, rest = train_test_split(df, test_size=0.3, stratify=df["label"], random_state=SEED)
    _, test_df = train_test_split(rest, test_size=0.5, stratify=rest["label"], random_state=SEED)
    model = SklearnTextClassifier(MODEL_DIR)
    if not model.available:
        raise SystemExit(f"content model failed to load: {model.error}")
    truth = list(test_df["label"])
    hybrid = HybridClassifier(model)
    return {"model": model.name,
            "sklearn": summary(truth, [model.classify(t)[0].value for t in test_df["text"]]),
            "hybrid_served": summary(truth, [hybrid.classify(t)[0].value for t in test_df["text"]]),
            "lexicon_baseline": summary(truth, [LexiconClassifier().classify(t)[0].value for t in test_df["text"]])}


def to_markdown(risk: dict[str, Any], content: dict[str, Any]) -> str:
    lines = ["# Model evaluation report (synthetic data)", "",
             "Generated by `ml/evaluation/evaluate.py` from the registered, SHA-256-verified artifacts on held-out simulated",
             "users. **All data is synthetic**; these numbers validate the pipeline, not real-world performance.", "",
             "## B. Risk prediction (test split)", "",
             "| Target | Model | ROC-AUC | PR-AUC | Brier | ECE | Precision@0.5 | Recall@0.5 | Rules ROC-AUC | Rules ECE |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for target in TARGETS:
        m, r = risk[target]["model"], risk[target]["rules_baseline"]
        lines.append(f"| {target} | {risk[target]['version']} | {m['roc_auc']:.3f} | {m['pr_auc']:.3f} | {m['brier']:.3f} | {m['ece']:.3f} | "
                     f"{m['precision']:.3f} | {m['recall']:.3f} | {r['roc_auc']:.3f} | {r['ece']:.3f} |")
    lines += ["", "Distraction ROC-AUC by persona (test users): " + ", ".join(f"{k} {v:.3f}" for k, v in risk["by_persona_distraction_auc"].items()),
              "", "## A. Content classification (test split)", "", "| Classifier | Accuracy | Macro precision | Macro recall | Macro F1 |", "|---|---|---|---|---|"]
    for key in ("sklearn", "hybrid_served", "lexicon_baseline"):
        s = content[key]
        lines.append(f"| {key} | {s['accuracy']:.3f} | {s['macro_precision']:.3f} | {s['macro_recall']:.3f} | {s['macro_f1']:.3f} |")
    lines += ["", "Figures: `figures/risk_calibration_*.png`, `figures/content_confusion_matrix.png`.", ""]
    return "\n".join(lines)


def main() -> None:
    risk, content = evaluate_risk(), evaluate_content()
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    (REPORT_DIR / "evaluation.json").write_text(json.dumps({"risk": risk, "content": content}, indent=2))
    (REPORT_DIR / "evaluation_report.md").write_text(to_markdown(risk, content))
    trained = json.loads((REPORT_DIR / "risk_metrics.json").read_text())
    for target in TARGETS:
        served, reported = risk[target]["model"]["roc_auc"], trained["targets"][target]["test_calibrated"]["roc_auc"]
        assert abs(served - reported) < 1e-3, (target, served, reported)
    print(to_markdown(risk, content))
    print("served models reproduce the training report:", bool(np.isfinite(1)))


if __name__ == "__main__":
    main()
